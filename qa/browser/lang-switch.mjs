import { chromium } from "playwright";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
const p = await ctx.newPage();
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
await p.goto("http://127.0.0.1:3100/app/diagnostics", { waitUntil: "networkidle" });
await p.evaluate(() => localStorage.setItem("wfm-locale", "es"));
await p.reload({ waitUntil: "networkidle" });
const seeEs = await p.evaluate(() => document.body.innerText);
const hasDemo = /Cargar datos demo|Datos demo/.test(seeEs);
await p.evaluate(() => localStorage.setItem("wfm-locale", "en"));
await p.reload({ waitUntil: "networkidle" });
const seeEn = await p.evaluate(() => document.body.innerText);
const label = await p.$eval('button[aria-label]', (el) => el.getAttribute("aria-label")).catch(() => null);
console.log("ES page shows Spanish findings title:", /Déficit de personal|Sobredotación|Sin datos/.test(seeEs));
console.log("EN page shows English findings title:", /Staffing deficit|Overstaffing|No interval data/.test(seeEn));
console.log("EN page still shows Spanish phrases:", /Déficit total|Costo cargado|Exportar informe/.test(seeEn));
console.log("re-run aria-label (last):", label);
console.log("page errors:", errors.length, errors.slice(0,3));
await b.close();
